package org.fxboomk.fcitx5.android.data.pinyin

import kotlinx.serialization.Serializable

@Serializable
data class CustomShuangpinScheme(
    val name: String = CustomShuangpinSchemeCodec.DEFAULT_NAME,
    val zeroInitial: String = CustomShuangpinSchemeCodec.DEFAULT_ZERO_INITIAL,
    val initials: Map<String, String> = emptyMap(),
    val finals: Map<String, String> = emptyMap(),
    /** Full pinyin syllable -> one or more explicit two-key inputs. */
    val syllables: Map<String, List<String>> = emptyMap()
)

/**
 * Pure conversion between the app's structured custom shuangpin scheme and the
 * `sp.dat` format consumed by libime.
 */
object CustomShuangpinSchemeCodec {
    const val DEFAULT_NAME = "自定义双拼"
    const val DEFAULT_ZERO_INITIAL = "*"
    const val NONE = "__none__"

    val INITIALS = listOf(
        "b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j", "q", "x",
        "zh", "ch", "sh", "r", "z", "c", "s", "y", "w"
    )

    val FINALS = listOf(
        "a", "o", "e", "i", "u", "v",
        "ai", "ei", "ui", "ao", "ou", "iu", "ie", "ue", "ve", "er",
        "an", "en", "in", "un", "ang", "eng", "ing", "ong",
        "ia", "iao", "ian", "iang", "iong", "ua", "uo", "uai", "uan", "uang", "ng"
    )

    /** Keys offered by the editor. `;` is kept for compatibility with schemes
     * such as Microsoft/Ziguang that use it for `ing`. */
    val KEYS = ('a'..'z').map(Char::toString) + ";"

    /** These names make libime ignore all following custom mappings. */
    val BUILTIN_NAMES = setOf(
        "自然码", "微软", "紫光", "拼音加加", "中文之星", "智能ABC", "小鹤"
    )

    fun defaultScheme(): CustomShuangpinScheme = CustomShuangpinScheme(
        initials = mapOf("zh" to "v", "ch" to "i", "sh" to "u"),
        finals = mapOf(
            "ai" to "d", "an" to "j", "ang" to "h", "ao" to "c",
            "ei" to "w", "en" to "f", "eng" to "g",
            "ia" to "x", "ian" to "m", "iang" to "l", "iao" to "n",
            "ie" to "p", "in" to "b", "ing" to "k", "iong" to "s",
            "iu" to "q", "ong" to "s", "ou" to "z", "ua" to "x",
            "uai" to "k", "uan" to "r", "uang" to "l", "ue" to "t",
            "ui" to "v", "un" to "y", "uo" to "o", "ve" to "t", "v" to "v"
        )
    )

    fun isValidName(name: String): Boolean {
        val trimmed = name.trim()
        return trimmed.isNotEmpty() &&
            trimmed.length <= 64 &&
            trimmed !in BUILTIN_NAMES &&
            trimmed.none { it == '\r' || it == '\n' }
    }

    fun isValidZeroInitial(value: String): Boolean {
        val trimmed = value.trim()
        return trimmed.isNotEmpty() && trimmed.all { it in 'a'..'z' || it == '*' }
    }

    fun isValidKey(key: String): Boolean = key.isEmpty() || key in KEYS

    fun isValidSyllable(pinyin: String): Boolean =
        pinyin.isNotEmpty() && pinyin.all { it in 'a'..'z' }

    fun isValidSyllableKeys(keys: String): Boolean =
        keys.length == 2 && keys.all { it in 'a'..'z' || it == ';' }

    fun toSpDat(scheme: CustomShuangpinScheme): String = buildString {
        appendLine("# Generated by Fcitx5 for Android. Edit this scheme in the app.")
        appendLine("[方案]")
        appendLine("方案名称=${scheme.name.trim()}")
        appendLine()
        appendLine("[零声母标识]")
        appendLine("=${scheme.zeroInitial.trim()}")
        appendLine()
        appendLine("[声母]")
        INITIALS.forEach { initial ->
            scheme.initials[initial]?.takeIf(String::isNotEmpty)?.let {
                appendLine("$initial=$it")
            }
        }
        appendLine()
        appendLine("[韵母]")
        FINALS.forEach { final ->
            scheme.finals[final]?.takeIf(String::isNotEmpty)?.let {
                appendLine("$final=$it")
            }
        }
        if (scheme.syllables.isNotEmpty()) {
            appendLine()
            appendLine("[音节]")
            scheme.syllables.forEach { (pinyin, keys) ->
                keys.forEach { key -> appendLine("$pinyin=$key") }
            }
        }
        appendLine()
    }

    fun parseSpDat(text: String): CustomShuangpinScheme {
        var name = DEFAULT_NAME
        var zeroInitial = "o"
        val initials = mutableMapOf<String, String>()
        val finals = mutableMapOf<String, String>()
        val syllables = mutableMapOf<String, MutableList<String>>()
        var section = ""

        for (rawLine in text.lineSequence()) {
            val line = rawLine.trim()
            if (line.isEmpty() || line.startsWith('#')) continue
            if (line.startsWith('[') && line.endsWith(']')) {
                section = line.substring(1, line.length - 1)
                continue
            }
            if (line.startsWith("方案名称=")) {
                name = line.substringAfter('=').trim().ifEmpty { DEFAULT_NAME }
                continue
            }
            if (line.startsWith('=') && line.length > 1) {
                zeroInitial = line.substring(1).trim().lowercase().ifEmpty { "o" }
                continue
            }

            val separator = line.indexOf('=')
            if (separator <= 0 || separator == line.lastIndex) continue
            val component = line.substring(0, separator).trim()
            val key = line.substring(separator + 1).trim().lowercase()

            if (section == "音节" || section == "Syllables") {
                if (isValidSyllable(component) && isValidSyllableKeys(key)) {
                    syllables.getOrPut(component) { mutableListOf() }.add(key)
                }
                continue
            }

            if (key.length != 1 || key !in KEYS) continue
            when (section) {
                "声母", "Initials" -> if (component in INITIALS) initials[component] = key
                "韵母", "Finals" -> if (component in FINALS) finals[component] = key
            }
        }

        return CustomShuangpinScheme(
            name = name,
            zeroInitial = zeroInitial,
            initials = initials,
            finals = finals,
            syllables = syllables.mapValues { it.value.distinct() }
        )
    }
}
